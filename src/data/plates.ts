import type { PlateCard, Rarity } from '../types/game'

/** 画心卡。编号对应 src/assets/plates 里的文件。 */
function plate(
  seriesId: string,
  no: number,
  rarity: Rarity,
  name: string,
  verse: string,
  flavor: string,
  notes: readonly [string, string, string],
): PlateCard {
  const index = String(no).padStart(2, '0')
  return {
    id: `${seriesId}-${index}`,
    seriesId,
    no,
    name,
    rarity,
    face: 'plate',
    art: `${seriesId}/${index}`,
    verse,
    flavor,
    notes,
  }
}

